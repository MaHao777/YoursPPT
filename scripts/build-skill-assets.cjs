'use strict';
// Mechanical generation only: upstream files are read, never rewritten.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const crypto = require('node:crypto');
const { once } = require('node:events');
const root = path.resolve(__dirname, '..');
const targets = [
  { key: 'guizang', output: 'guizang.js', source: 'vendor/guizang-ppt-skill', url: 'https://github.com/op7418/guizang-ppt-skill' },
  { key: 'pptMaster', output: 'ppt-master.js', source: 'vendor/ppt-master-vendored/skills/ppt-master', url: 'https://github.com/hugohe3/ppt-master' }
];
// Exclude VCS internals and actual caches, not fonts, dependencies or asset trees.
const caches = new Set(['.git', '__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache', '.cache']);
function walk(directory, prefix = '') {
  const result = [];
  for (const item of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    if (caches.has(item.name) || /\.py[co]$/u.test(item.name)) continue;
    const relative = prefix + item.name, absolute = path.join(directory, item.name);
    if (item.isSymbolicLink()) throw new Error('Cannot silently omit symlink: ' + absolute);
    if (item.isDirectory()) {
      result.push({ name: relative + '/', directory: true });
      result.push(...walk(absolute, relative + '/'));
    } else if (item.isFile()) result.push({ name: relative, absolute });
    else throw new Error('Unsupported upstream entry: ' + absolute);
  }
  return result;
}
const table = new Uint32Array(256);
for (let n = 0; n < 256; n++) {
  let c = n;
  for (let k = 0; k < 8; k++) c = (c >>> 1) ^ ((c & 1) ? 0xedb88320 : 0);
  table[n] = c >>> 0;
}
function crc32(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) c = table[(c ^ b) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
async function generate(target) {
  const entries = walk(path.join(root, target.source));
  if (!entries.some(e => e.name === 'SKILL.md') || !entries.some(e => e.name === 'LICENSE')) {
    throw new Error('Missing entry point or license: ' + target.source);
  }
  const output = path.join(root, 'assets', 'skills', target.output);
  const temporary = output + '.tmp';
  const stream = fs.createWriteStream(temporary, { encoding: 'utf8' });
  // Handle errors from both buffered writes and the final flush.
  let failure;
  stream.on('error', error => { failure = error; });
  async function write(text) {
    if (failure) throw failure;
    if (!stream.write(text)) await once(stream, 'drain');
  }
  let files = 0, directories = 0, size = 0, compressedSize = 0;
  const digest = crypto.createHash('sha256');
  await write('// Generated by scripts/build-skill-assets.cjs; complete upstream snapshot, licenses retained.\n(function(root){"use strict";var Y=root.YoursPPT=root.YoursPPT||{};Y.SKILL_BUNDLES=Y.SKILL_BUNDLES||{};Y.SKILL_BUNDLES[' + JSON.stringify(target.key) + ']={format:1,source:' + JSON.stringify(target.source) + ',upstream:' + JSON.stringify(target.url) + ',entries:[\n');
  try {
    for (let i = 0; i < entries.length; i++) {
      const entry = entries[i];
      let record;
      if (entry.directory) {
        directories++;
        record = { name: entry.name, base64: '', crc: 0, size: 0, method: 0 };
      } else {
        const raw = fs.readFileSync(entry.absolute);
        const compressed = zlib.deflateRawSync(raw, { level: 9 });
        record = { name: entry.name, base64: compressed.toString('base64'), crc: crc32(raw), size: raw.length, method: 8 };
        digest.update(entry.name + '\0').update(raw);
        files++; size += raw.length; compressedSize += compressed.length;
      }
      await write(JSON.stringify(record) + (i === entries.length - 1 ? '\n' : ',\n'));
      if (files && files % 2000 === 0 && !entry.directory) console.log(target.key + ': ' + files + ' files compressed');
    }
    const stats = { files, directories, size, compressedSize, sha256: digest.digest('hex') };
    await write('],stats:' + JSON.stringify(stats) + '};if(typeof module!=="undefined"&&module.exports)module.exports=Y.SKILL_BUNDLES[' + JSON.stringify(target.key) + '];}(typeof window!=="undefined"?window:globalThis));\n');
    const finished = once(stream, 'finish');
    stream.end(); await finished;
    if (failure) throw failure;
    fs.renameSync(temporary, output);
    console.log(target.key + ': ' + JSON.stringify(stats) + ' -> ' + output);
    return stats;
  } catch (error) {
    stream.destroy();
    throw error;
  }
}
async function main() {
  fs.mkdirSync(path.join(root, 'assets', 'skills'), { recursive: true });
  for (const target of targets) await generate(target);
}
if (require.main === module) main().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { walk, crc32, generate };
